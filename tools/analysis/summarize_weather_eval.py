#!/usr/bin/env python3
"""Summarize per-epoch weather-group metrics into CSV/Markdown.

Expected input directory structure (generated by WeatherEvalHook):
    <work_dir>/weather_eval/epoch_001.json
    <work_dir>/weather_eval/epoch_002.json
    ...

Each json file should contain:
{
  "epoch": 1,
  "groups": {
    "rain": {"NDS": 0.52, "mAP": 0.41},
    "night": {"NDS": 0.49, "mAP": 0.38},
    "day": {"NDS": 0.62, "mAP": 0.50}
  }
}
"""

import argparse
import csv
import glob
import json
import os
from typing import Dict, List, Tuple


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description='Summarize weather_eval epoch json files to CSV/Markdown.')
    parser.add_argument(
        '--weather-dir',
        required=True,
        help='Directory containing epoch_XXX.json files, e.g. work_dirs/xxx/weather_eval')
    parser.add_argument(
        '--out-csv',
        default=None,
        help='Output CSV path. Default: <weather-dir>/summary_weather_metrics.csv')
    parser.add_argument(
        '--out-md',
        default=None,
        help='Optional markdown output path. Default: <weather-dir>/summary_weather_metrics.md')
    parser.add_argument(
        '--groups',
        nargs='+',
        default=['rain', 'night', 'day'],
        help='Weather groups to summarize, default: rain night day')
    return parser.parse_args()


def _safe_float(value):
    if value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _discover_epoch_files(weather_dir: str) -> List[str]:
    pattern = os.path.join(weather_dir, 'epoch_*.json')
    files = sorted(glob.glob(pattern))
    return files


def _load_epoch_record(path: str, groups: List[str]) -> Dict[str, object]:
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    epoch = data.get('epoch')
    if epoch is None:
        base = os.path.basename(path)
        digits = ''.join(ch for ch in base if ch.isdigit())
        epoch = int(digits) if digits else -1

    groups_data = data.get('groups', {})

    row = {'epoch': int(epoch)}
    for group in groups:
        metrics = groups_data.get(group, {}) if isinstance(groups_data, dict) else {}
        row[f'{group}_NDS'] = _safe_float(metrics.get('NDS'))
        row[f'{group}_mAP'] = _safe_float(metrics.get('mAP'))

    return row


def _write_csv(rows: List[Dict[str, object]], out_csv: str, groups: List[str]) -> None:
    os.makedirs(os.path.dirname(out_csv), exist_ok=True)
    fieldnames = ['epoch']
    for group in groups:
        fieldnames.extend([f'{group}_NDS', f'{group}_mAP'])

    with open(out_csv, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def _fmt(val) -> str:
    if val is None:
        return 'NA'
    return f'{val:.4f}'


def _write_md(rows: List[Dict[str, object]], out_md: str, groups: List[str]) -> None:
    os.makedirs(os.path.dirname(out_md), exist_ok=True)
    headers = ['epoch']
    for group in groups:
        headers.extend([f'{group}_NDS', f'{group}_mAP'])

    lines = []
    lines.append('| ' + ' | '.join(headers) + ' |')
    lines.append('|' + '|'.join(['---'] * len(headers)) + '|')

    for row in rows:
        vals = [str(row['epoch'])]
        for group in groups:
            vals.append(_fmt(row.get(f'{group}_NDS')))
            vals.append(_fmt(row.get(f'{group}_mAP')))
        lines.append('| ' + ' | '.join(vals) + ' |')

    with open(out_md, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


def _best_epochs(rows: List[Dict[str, object]], groups: List[str]) -> List[Tuple[str, int, float]]:
    results = []
    for group in groups:
        for metric in ['NDS', 'mAP']:
            key = f'{group}_{metric}'
            valid = [(int(r['epoch']), r.get(key)) for r in rows if r.get(key) is not None]
            if not valid:
                continue
            best_epoch, best_value = max(valid, key=lambda x: x[1])
            results.append((key, best_epoch, float(best_value)))
    return results


def main() -> int:
    args = parse_args()
    weather_dir = os.path.abspath(args.weather_dir)

    if not os.path.isdir(weather_dir):
        print(f'[ERROR] weather_dir not found: {weather_dir}')
        return 1

    epoch_files = _discover_epoch_files(weather_dir)
    if not epoch_files:
        print(f'[ERROR] no epoch_*.json found in: {weather_dir}')
        return 1

    rows = [_load_epoch_record(path, args.groups) for path in epoch_files]
    rows = sorted(rows, key=lambda x: int(x['epoch']))

    out_csv = args.out_csv or os.path.join(weather_dir, 'summary_weather_metrics.csv')
    _write_csv(rows, out_csv, args.groups)

    out_md = args.out_md or os.path.join(weather_dir, 'summary_weather_metrics.md')
    _write_md(rows, out_md, args.groups)

    print(f'[OK] CSV written: {out_csv}')
    print(f'[OK] MD written: {out_md}')
    print('[INFO] Best epochs:')
    for key, epoch, value in _best_epochs(rows, args.groups):
        print(f'  - {key}: epoch={epoch}, value={value:.4f}')

    return 0


if __name__ == '__main__':
    raise SystemExit(main())
